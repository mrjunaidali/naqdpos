-- migrate:up
-- Staging rejected an ml product (bug 2026-11-25, "The data was not valid"). Three parts:
--
-- 1. The ml unit checks again, idempotently. 20261125090000_ml_unit.sql already sets them, and old
--    migrations are never edited (CLAUDE.md rule 8); this only acts on a database whose checks
--    still lack 'ml', and does nothing (no table rewrite, no lock) where they have it.
-- 2. sync_units(): the units the database accepts, sent on every pull so a device holds back
--    rows with a unit the server does not know yet (deploy-order safeguard). A migration that
--    changes either unit check must update it too (db/tests/sync-units.test.ts compares them).
-- 3. sync_push: an 'invalid' rejection also names the failed column in 'field' when Postgres
--    knows it. The error object only gains a key, so older apps read it as before.

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.products'::regclass and conname = 'products_unit_check'
      and pg_get_constraintdef(oid) like '%''ml''%') then
    alter table public.products drop constraint if exists products_unit_check;
    alter table public.products add constraint products_unit_check
      check (unit in ('kg', 'g', 'dozen', 'piece', 'bundle', 'litre', 'ml'));
  end if;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.sale_lines'::regclass and conname = 'sale_lines_unit_snapshot_check'
      and pg_get_constraintdef(oid) like '%''ml''%') then
    alter table public.sale_lines drop constraint if exists sale_lines_unit_snapshot_check;
    alter table public.sale_lines add constraint sale_lines_unit_snapshot_check
      check (unit_snapshot in ('kg', 'g', 'dozen', 'piece', 'bundle', 'litre', 'ml'));
  end if;
end;
$$;

