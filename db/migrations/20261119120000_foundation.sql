-- ---------------------------------------------------------------------------
-- Access helpers. security definer so policies can read memberships/platform_admins
-- without recursing into their RLS. They only answer questions about the caller.
-- ---------------------------------------------------------------------------
create function public.is_shop_member(p_shop_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.memberships m
    where m.shop_id = p_shop_id
      and m.user_id = (select public.current_user_id())
      and m.deleted_at is null
  );
$$;

create function public.has_shop_role(p_shop_id uuid, p_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.memberships m
    where m.shop_id = p_shop_id
      and m.user_id = (select public.current_user_id())
      and m.deleted_at is null
      and m.role = any (p_roles)
  );
$$;

create function public.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.platform_admins pa where pa.user_id = (select public.current_user_id())
  );
$$;

