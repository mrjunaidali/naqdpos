create sequence public.server_seq as bigint;
revoke all on sequence public.server_seq from public;

-- security definer so naqdpos_app never needs USAGE on the sequence; it also overrides any
-- server_seq value a client sends.
create function public.set_server_seq()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.server_seq := nextval('public.server_seq');
  return new;
end;
$$;
revoke all on function public.set_server_seq() from public;

