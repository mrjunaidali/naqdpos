-- Foundation: database roles, Better Auth tables, current_user_id(), server_seq, and the tenancy
-- tables (shops, memberships, staff, staff_salaries, devices, platform_admins, audit_log).
-- Conventions: docs/architecture.md §2. Access rules: §5.
--
-- Migrations run as the owner role (DATABASE_ADMIN_URL), which owns every object. The API
-- connects as naqdpos_app: it owns nothing and has no BYPASSRLS, so RLS always applies to it.
-- Synced-table ids come from the device (UUIDv7, CLAUDE.md rule 2), so those id columns have
-- no default. Enumerations are text + check (not Postgres enums) so values can be added without
-- enum migrations.

-- ---------------------------------------------------------------------------
-- Roles. Roles are cluster-wide: create naqdpos_app only if it is missing. Locally
-- `pnpm db:create` makes it a login role with a password first; on a host, ops runs
-- `alter role naqdpos_app login password '...'` once. Passwords never go in migrations.
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'naqdpos_app') then
    create role naqdpos_app nologin nosuperuser nocreatedb nocreaterole noinherit nobypassrls;
  end if;
end;
$$;

revoke create on schema public from public;
grant usage on schema public to naqdpos_app;
-- New functions are not callable by everyone; each one is granted explicitly below.
alter default privileges revoke execute on functions from public;

-- ---------------------------------------------------------------------------
-- current_user_id(): the signed-in user of this transaction. The API runs every request in a
-- transaction that first does set_config('app.user_id', <id>, true); empty or unset = nobody.
-- ---------------------------------------------------------------------------
create function public.current_user_id()
returns uuid
language sql
stable
as $$
  select nullif(current_setting('app.user_id', true), '')::uuid;
$$;
revoke all on function public.current_user_id() from public;
grant execute on function public.current_user_id() to naqdpos_app;

