-- Better Auth needs these rows before any user is known (to look up a session token), so the
-- policies key on the connection's app.context instead of the user. Only Better Auth's own pool
-- starts connections with app.context = 'auth'; tenant request transactions never set it, so a
-- tenant query cannot read sessions, tokens or TOTP secrets.
alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.accounts enable row level security;
alter table public.verifications enable row level security;
alter table public.two_factors enable row level security;

grant select, insert, update, delete
